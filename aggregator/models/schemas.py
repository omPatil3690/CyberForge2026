"""
aggregator/models/schemas.py — Pydantic v2 response models for the CyberForge aggregation API.

Every model uses ``model_config = ConfigDict(from_attributes=True)`` so that
instances can be constructed directly from ORM-like row objects as well as
plain dicts.

Numeric fields sourced from DuckDB NUMERIC columns (which arrive as Python
``decimal.Decimal``) are typed as ``float`` with automatic coercion; Pydantic
v2 performs this conversion natively when ``coerce_numbers_to_str=False``
(the default).
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


# ---------------------------------------------------------------------------
# Shared freshness mixin
# ---------------------------------------------------------------------------

class FreshnessMixin(BaseModel):
    """Mixin that adds data-freshness metadata fields to every response."""

    model_config = ConfigDict(from_attributes=True)

    data_freshness_seconds: float = Field(
        ...,
        description="Seconds elapsed since the last successful DuckDB sync.",
    )
    last_synced_at: datetime | None = Field(
        None,
        description="UTC timestamp of the most recent completed sync cycle.",
    )


# ---------------------------------------------------------------------------
# FR-1 — Summary
# ---------------------------------------------------------------------------

class SummaryResponse(FreshnessMixin):
    """Response body for GET /tenants/{tenant_id}/metrics/summary.

    Attributes:
        tenant_id:          The tenant whose data was queried.
        order_count:        Total number of orders in the requested date range.
        total_revenue:      Sum of ``total_amount`` for all matched orders.
        avg_order_value:    Mean ``total_amount`` across matched orders.
        from_date:          Inclusive start of the query window (ISO-8601).
        to_date:            Inclusive end of the query window (ISO-8601).
        data_freshness_seconds: Seconds since last sync.
        last_synced_at:     Timestamp of last sync.
    """

    tenant_id: int
    order_count: int
    total_revenue: float
    avg_order_value: float
    from_date: datetime
    to_date: datetime


# ---------------------------------------------------------------------------
# FR-2 — Trend
# ---------------------------------------------------------------------------

class TrendDataPoint(BaseModel):
    """A single time-bucket in the trend series.

    Attributes:
        period:      ISO-8601 string representing the bucket start
                     (e.g. ``"2026-10-01"`` for a daily bucket).
        order_count: Number of orders that fall in this bucket.
        revenue:     Total revenue within this bucket.
    """

    model_config = ConfigDict(from_attributes=True)

    period: str
    order_count: int
    revenue: float


class TrendResponse(FreshnessMixin):
    """Response body for GET /tenants/{tenant_id}/metrics/trend.

    Attributes:
        tenant_id: The tenant whose data was queried.
        interval:  Granularity used (``"hour"`` or ``"day"``).
        data:      Ordered list of ``TrendDataPoint`` objects.
        data_freshness_seconds: Seconds since last sync.
        last_synced_at:     Timestamp of last sync.
    """

    tenant_id: int
    interval: str
    data: list[TrendDataPoint]


# ---------------------------------------------------------------------------
# FR-3 — Top Products
# ---------------------------------------------------------------------------

class TopProductItem(BaseModel):
    """A single product entry in the top-products response.

    Attributes:
        rank:            1-based ranking position (by total revenue descending).
        product_id:      Primary key of the product.
        name:            Display name of the product.
        category:        Product category string.
        total_quantity:  Total units sold in the requested period.
        total_revenue:   Total revenue generated by this product.
    """

    model_config = ConfigDict(from_attributes=True)

    rank: int
    product_id: int
    name: str
    category: str
    total_quantity: int
    total_revenue: float


class TopProductsResponse(FreshnessMixin):
    """Response body for GET /tenants/{tenant_id}/metrics/top-products.

    Attributes:
        tenant_id: The tenant whose data was queried.
        limit:     Maximum number of products returned.
        data:      Ordered list of ``TopProductItem`` objects.
        data_freshness_seconds: Seconds since last sync.
        last_synced_at:     Timestamp of last sync.
    """

    tenant_id: int
    limit: int
    data: list[TopProductItem]


# ---------------------------------------------------------------------------
# FR-4 — Status Breakdown
# ---------------------------------------------------------------------------

class StatusBreakdownItem(BaseModel):
    """A single order-status bucket in the breakdown response.

    Attributes:
        status:     One of ``placed``, ``shipped``, ``delivered``, ``cancelled``.
        count:      Number of orders with this status.
        revenue:    Total revenue from orders with this status.
        percentage: Fraction of total orders (0–100, rounded to 2 d.p.).
    """

    model_config = ConfigDict(from_attributes=True)

    status: str
    count: int
    revenue: float
    percentage: float


class StatusBreakdownResponse(FreshnessMixin):
    """Response body for GET /tenants/{tenant_id}/metrics/breakdown/status.

    Attributes:
        tenant_id:    The tenant whose data was queried.
        data:         One ``StatusBreakdownItem`` per distinct order status.
        total_orders: Sum of all status counts (convenience field).
        data_freshness_seconds: Seconds since last sync.
        last_synced_at:     Timestamp of last sync.
    """

    tenant_id: int
    data: list[StatusBreakdownItem]
    total_orders: int


# ---------------------------------------------------------------------------
# Admin — Health
# ---------------------------------------------------------------------------

class HealthResponse(BaseModel):
    """Response body for GET /admin/health.

    Attributes:
        status:                  ``"ok"`` when the service is healthy.
        last_synced_at:          UTC timestamp of the last completed sync.
        data_freshness_seconds:  Seconds elapsed since the last sync.
        sync_lag_seconds:        Duration of the most recent sync cycle.
        duckdb_order_count:      Total rows in the DuckDB ``orders`` table.
        pg_order_count_estimate: Approximate row count from PostgreSQL
                                 ``pg_class.reltuples`` (fast, non-locking).
        uptime_seconds:          API process uptime in seconds.
    """

    model_config = ConfigDict(from_attributes=True)

    status: str
    last_synced_at: datetime | None
    data_freshness_seconds: float
    sync_lag_seconds: float
    duckdb_order_count: int
    pg_order_count_estimate: int
    uptime_seconds: float


# ---------------------------------------------------------------------------
# Admin — Metrics
# ---------------------------------------------------------------------------

class AdminMetricsResponse(BaseModel):
    """Response body for GET /admin/metrics.

    Tracks rolling performance statistics across the last 1 000 requests.

    Attributes:
        query_latency_p50_ms: Median query latency in milliseconds.
        query_latency_p95_ms: 95th-percentile query latency.
        query_latency_p99_ms: 99th-percentile query latency.
        sync_interval_seconds: Configured sync polling interval.
        last_sync_row_count:   Number of rows upserted in the last sync cycle.
        total_syncs:           Cumulative number of completed sync cycles.
        cache_hit_ratio:       Placeholder — always 1.0 (all queries hit DuckDB,
                               never PostgreSQL).
    """

    model_config = ConfigDict(from_attributes=True)

    query_latency_p50_ms: float
    query_latency_p95_ms: float
    query_latency_p99_ms: float
    sync_interval_seconds: int
    last_sync_row_count: int
    total_syncs: int
    cache_hit_ratio: float


